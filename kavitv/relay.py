#!/usr/bin/env python3
"""KaviTV relay v2.0 — hardened rebuild. No duct tape.

What changed from v1.x:
  1. Structured logging to rotating files (was: log_message no-op).
  2. Timeline manager: cached, hot-reloaded on mtime change, schema-
     validated on every load (was: re-read + parsed per request, no validation).
  3. ffmpeg supervisor: per-connection deadline, stall detection (no bytes
     for STALL_TIMEOUT mid-stream kills the process), SIGTERM -> 5s ->
     SIGKILL escalation with proc.wait() reaping (no zombies).
     (was: first-byte timeout only, terminate-or-kill without reaping.)
  4. Slate fallback: if the source fails after retries, serve a generated
     "KAVITV - PLEASE STANDBY" slate via ffmpeg testsrc instead of HTTP 502,
     so the tuner never sees an error (was: 502, tuner shows error).
  5. Deep health check at /api/deep-health: validates timeline, ffmpeg,
     and actually probes that a stream can start (was: /api/health only
     reported static facts; a wedged relay still returned ok:true).
  6. Startup validation: ffmpeg exists, timeline valid, emby.key readable,
     port free — exits with distinct codes and a clear log line otherwise.
  7. Child-process registry: every spawned ffmpeg PID tracked; on shutdown
     all children are reaped (was: orphaned ffmpeg processes possible).

Architecture (unchanged from v1):
  The relay OWNS ffmpeg. Emby is a dumb byte source via
  /emby/Videos/<id>/stream?static=true. Per tune-in the relay spawns
  ffmpeg with a SINGLE input -ss, stream-copy to MPEG-TS, pipes stdout.

Endpoints:
  GET /kavitv/live/<slug>[.m3u8] -> 200 video/mp2t, live MPEG-TS
  GET /api/health                 -> {ok, version, ...} (lightweight)
  GET /api/deep-health            -> {ok, checks:{...}} (for watchdogs)

Config (C:\\Users\\sethr\\kavitv\\config\\):
  emby.key       API key (never logged)
  timeline.json  generated by generate.py (hot-reloaded)

Logs: C:\\Users\\sethr\\kavitv\\logs\\relay.log (10 MB rotation x5)

Run:  python relay.py [--port 8100]
      (production: via NSSM service, see relay-deploy.md)
"""

