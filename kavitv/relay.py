# Timeline manager (cached, hot-reloaded, validated)
# --------------------------------------------------------------------------

class TimelineManager:
    def __init__(self, path):
        self.path = path
        self._lock = threading.Lock()
        self._data = None
        self._mtime = 0

    def _validate(self, tl):
        if not isinstance(tl, dict):
            raise ValueError("timeline root must be an object")
        channels = tl.get("channels")
        if not isinstance(channels, dict) or not channels:
            raise ValueError("timeline.channels missing or empty")
        for cid, ch in channels.items():
            slots = ch.get("slots")
            if not isinstance(slots, list) or not slots:
                raise ValueError(f"channel {cid}: no slots")
            for s in slots:
                for field in ("start", "end", "title", "emby_id"):
                    if field not in s:
                        raise ValueError(
                            f"channel {cid}: slot missing {field}")
                # start/end must parse
                datetime.fromisoformat(s["start"])
                datetime.fromisoformat(s["end"])
        return tl

    def get(self):
        """Return cached timeline, reloading if the file changed."""
        try:
            mtime = os.path.getmtime(self.path)
        except OSError as e:
            raise FileNotFoundError(f"timeline.json unreadable: {e}")
        with self._lock:
            if self._data is not None and mtime == self._mtime:
                return self._data
            with open(self.path, encoding="utf-8") as f:
                raw = json.load(f)
            self._data = self._validate(raw)
            self._mtime = mtime
            n_slots = sum(len(c["slots"])
                          for c in self._data["channels"].values())
            log.info("timeline loaded: %d channels, %d slots (mtime=%s)",
                     len(self._data["channels"]), n_slots, mtime)
            return self._data

    def invalidate(self):
        with self._lock:
            self._data = None


TIMELINE = TimelineManager(TIMELINE_FILE)


def current_program(timeline, cid):
    """(slot, offset_sec) for what's airing now on timeline channel `cid`."""
    slots = timeline["channels"][cid]["slots"]
    now = datetime.now(timezone.utc)
    lo, hi = 0, len(slots) - 1
    while lo <= hi:
        mid = (lo + hi) // 2
        s = datetime.fromisoformat(slots[mid]["start"])
        e = datetime.fromisoformat(slots[mid]["end"])
        if e <= now:
            lo = mid + 1
        elif s > now:
            hi = mid - 1
        else:
            if (e - now).total_seconds() < 10 and mid + 1 < len(slots):
                return slots[mid + 1], 0.0
            dur = (e - s).total_seconds()
            offset = max(0.0, min((now - s).total_seconds(), dur - 10.0))
            return slots[mid], offset
    return None, 0.0


def load_key():
    with open(KEY_FILE, encoding="utf-8") as f:
        return f.read().strip()


def static_url(item_id, api_key):
    q = urllib.parse.urlencode({"static": "true", "api_key": api_key})
    return f"{EMBY}/emby/Videos/{item_id}/stream?{q}"


