# --------------------------------------------------------------------------
# Child-process registry (no orphaned ffmpeg)
# --------------------------------------------------------------------------

class ChildRegistry:
    """Tracks every spawned ffmpeg so shutdown reaps them all."""

    def __init__(self):
        self._lock = threading.Lock()
        self._procs = set()

    def add(self, proc):
        with self._lock:
            self._procs.add(proc)

    def discard(self, proc):
        with self._lock:
            self._procs.discard(proc)

    def kill_all(self):
        with self._lock:
            procs = list(self._procs)
        for proc in procs:
            reap_process(proc, "shutdown")
        with self._lock:
            self._procs.clear()


CHILDREN = ChildRegistry()


def reap_process(proc, reason=""):
    """SIGTERM -> wait 5s -> SIGKILL -> wait. Never leaves a zombie."""
    if proc is None or proc.poll() is not None:
        return
    try:
        proc.terminate()
    except Exception:
        pass
    try:
        proc.wait(timeout=5)
        log.debug("reaped pid=%s reason=%s (terminate)", proc.pid, reason)
        return
    except Exception:
        pass
    try:
        proc.kill()
    except Exception:
        pass
    try:
        proc.wait(timeout=5)
        log.warning("force-killed pid=%s reason=%s", proc.pid, reason)
    except Exception:
        log.error("could not reap pid=%s reason=%s", proc.pid, reason)


