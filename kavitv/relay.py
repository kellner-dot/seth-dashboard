def validate_startup():
    """Exit codes: 2=ffmpeg, 3=timeline, 4=emby.key, 5=port in use."""
    if not os.path.exists(FFMPEG):
        log.critical("FATAL: ffmpeg not found at %s", FFMPEG)
        return 2
    try:
        TIMELINE.get()
    except Exception as e:  # noqa: BLE001
        log.critical("FATAL: timeline invalid: %s", e)
        return 3
    try:
        key = load_key()
        if not key:
            raise ValueError("empty")
    except Exception as e:  # noqa: BLE001
        log.critical("FATAL: emby.key unreadable: %s", e)
        return 4
    import socket
    s = socket.socket()
    try:
        s.bind(("0.0.0.0", PORT))
    except OSError as e:
        log.critical("FATAL: port %d in use: %s", PORT, e)
        return 5
    finally:
        s.close()
    return 0


PORT = 8100


def main():
    global PORT
    if "--port" in sys.argv:
        PORT = int(sys.argv[sys.argv.index("--port") + 1])

    code = validate_startup()
    if code:
        sys.exit(code)

    # Re-read timeline if generate.py rewrote it (mtime check is in get(),
    # but log a line at startup so the log shows which generation we took).
    tl = TIMELINE.get()
    log.info("KaviTV relay %s starting on :%d (ffmpeg=%s)",
             VERSION, PORT, FFMPEG)
    log.info("channels: %s", sorted(tl["channels"].keys()))

    srv = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        log.info("shutting down, reaping %d children", len(CHILDREN._procs))
        CHILDREN.kill_all()
        srv.server_close()
        log.info("relay stopped")


if __name__ == "__main__":
    main()
