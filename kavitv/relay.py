class Handler(BaseHTTPRequestHandler):
    server_version = "KaviTV-Relay/2.0"

    def log_message(self, *a):
        pass  # we use structured logging

    def _json(self, code, obj):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _now_map(self, tl):
        out = {}
        for slug, cid in CHANNELS.items():
            try:
                slot, off = current_program(tl, cid)
            except Exception:
                slot, off = None, 0.0
            out[slug] = {"title": slot["title"] if slot else None,
                         "offset_sec": round(off, 1)}
        return out

    def _serve_channel(self, slug):
        cid = CHANNELS.get(slug)
        if not cid:
            return self._json(400, {"error": "bad channel"})
        tl = TIMELINE.get()
        slot, offset_sec = current_program(tl, cid)
        if not slot:
            return self._json(404, {"error": "nothing scheduled"})
        item_id = slot["emby_id"]
        title = slot.get("title", "?")
        api_key = load_key()
        src = static_url(item_id, api_key)
        label = f"{slug}/{title}"

        # Attempt plan: computed offset, then offset 0, then slate.
        # Backoff between attempts so a flapping source doesn't hot-loop.
        attempts = []
        if offset_sec > 1.0:
            attempts.append(("seek", offset_sec))
        attempts.append(("start", 0.0))

        last_err = None
        for i, (kind, off) in enumerate(attempts):
            if i > 0:
                time.sleep(RETRY_BACKOFF[min(i, len(RETRY_BACKOFF) - 1)])
            log.info("[%s] attempt %d/%d (%s @ %.1fs)",
                     label, i + 1, len(attempts), kind, off)
            try:
                proc = spawn_ffmpeg(src, off)
                stream_ffmpeg_to_client(self, proc, label)
                return  # served successfully
            except (TimeoutError, RuntimeError) as e:
                last_err = e
                log.warning("[%s] attempt %d failed: %s", label, i + 1, e)
                continue

        # All source attempts failed: serve slate instead of HTTP 502.
        log.error("[%s] source failed after %d attempts (%s); serving slate",
                  label, len(attempts), last_err)
        try:
            proc = spawn_slate(f"KAVITV {slug.upper()} - PLEASE STANDBY")
            stream_ffmpeg_to_client(self, proc, f"slate-{slug}")
        except Exception as e:  # noqa: BLE001
            log.error("[slate-%s] failed too: %s", slug, e)
            self._json(502, {"error": "source and slate failed"})

    def do_GET(self):
        try:
            path = urllib.parse.urlsplit(self.path).path

            if path == "/api/health":
                try:
                    tl = TIMELINE.get()
                    now = self._now_map(tl)
                    gen = tl.get("generated_at")
                    chs = sorted(tl["channels"].keys())
                except Exception as e:  # noqa: BLE001
                    return self._json(503, {"ok": False, "error": str(e)[:200]})
                return self._json(200, {
                    "ok": True, "version": VERSION,
                    "ffmpeg": os.path.exists(FFMPEG),
                    "generated_at": gen,
                    "channels": chs, "now": now,
                })

            if path == "/api/deep-health":
                # For watchdogs: actually validate everything a stream needs.
                checks = {}
                try:
                    tl = TIMELINE.get()
                    checks["timeline"] = "ok"
                    for slug, cid in CHANNELS.items():
                        slot, _ = current_program(tl, cid)
                        checks[f"channel:{slug}"] = (
                            "ok" if slot else "nothing-scheduled")
                except Exception as e:  # noqa: BLE001
                    checks["timeline"] = f"FAIL: {e}"[:200]
                checks["ffmpeg"] = ("ok" if os.path.exists(FFMPEG)
                                    else "FAIL: missing")
                try:
                    key = load_key()
                    checks["emby_key"] = "ok" if key else "FAIL: empty"
                except Exception as e:  # noqa: BLE001
                    checks["emby_key"] = f"FAIL: {e}"[:200]
                ok = all(v == "ok" or v == "nothing-scheduled"
                         for v in checks.values())
                return self._json(200 if ok else 503,
                                  {"ok": ok, "version": VERSION,
                                   "checks": checks})

            # Back-compat: parent tooling probed /health (wrong path in v1
            # docs). Accept it and point at the right one.
            if path == "/health":
                return self._json(200, {"ok": True,
                                        "note": "use /api/health",
                                        "version": VERSION})

            if path.startswith("/kavitv/live/"):
                slug = path.split("/")[3].split(".")[0]
                self._serve_channel(slug)
                return

            return self._json(404, {"error": "not found"})
        except FileNotFoundError as e:
            log.error("config missing: %s", e)
            return self._json(503, {"error": "not configured",
                                    "detail": str(e)[:200]})
        except Exception as e:  # noqa: BLE001
            # Relay must never die on a bad request.
            log.exception("unhandled error serving %s", self.path)
            try:
                return self._json(500, {"error": "internal",
                                        "detail": str(e)[:200]})
            except Exception:
                pass


