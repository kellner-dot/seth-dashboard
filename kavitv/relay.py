def spawn_ffmpeg(src_url, offset_sec):
    """Start ffmpeg: input-seek, stream-copy, MPEG-TS to stdout pipe."""
    cmd = [
        FFMPEG,
        "-hide_banner", "-nostats", "-loglevel", "error",
        "-fflags", "+genpts+discardcorrupt+igndts",
        "-ss", f"{offset_sec:.1f}",
        "-i", src_url,
        "-map", "0:v:0", "-map", "0:a:0",
        "-c:v", "copy", "-c:a", "copy",
        # -output_ts_offset keeps timestamps sane after seek without the
        # decode errors that -copyts -start_at_zero produced (2026-10-04).
        "-output_ts_offset", "0",
        "-f", "mpegts",
        "-mpegts_flags", "resend_headers",
        "-flush_packets", "1",
        "pipe:1",
    ]
    proc = subprocess.Popen(
        cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        stdin=subprocess.DEVNULL)
    CHILDREN.add(proc)
    return proc


def spawn_slate(text="KAVITV - PLEASE STANDBY"):
    """Generate a slate: test pattern + tone, as MPEG-TS to stdout.

    Used when the real source is unavailable so the tuner never sees
    an HTTP error mid-guide.
    """
    cmd = [
        FFMPEG,
        "-hide_banner", "-nostats", "-loglevel", "error",
        "-f", "lavfi", "-i",
        f"testsrc2=size=1280x720:rate=30",
        "-f", "lavfi", "-i",
        "sine=frequency=440:sample_rate=48000",
        "-vf",
        f"drawtext=text='{text}':fontcolor=white:fontsize=48:"
        "x=(w-text_w)/2:y=(h-text_h)/2",
        "-c:v", "libx264", "-preset", "ultrafast", "-tune", "zerolatency",
        "-c:a", "aac",
        "-f", "mpegts", "-flush_packets", "1",
        "pipe:1",
    ]
    proc = subprocess.Popen(
        cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        stdin=subprocess.DEVNULL)
    CHILDREN.add(proc)
    return proc


class StreamPump:
    """Pumps ffmpeg stdout through a queue with stall detection.

    Windows has no select() on pipes, so a reader thread feeds a queue
    and the consumer applies timeouts. Tracks bytes + last-byte time so
    a silently-stalled ffmpeg (connected but no frames) gets killed.
    """

    def __init__(self, proc, label=""):
        self.proc = proc
        self.label = label
        self.q = queue.Queue()
        self.bytes_out = 0
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._pump, daemon=True,
                                        name=f"pump-{proc.pid}")
        self._thread.start()

    def _pump(self):
        try:
            while not self._stop.is_set():
                chunk = self.proc.stdout.read(CHUNK)
                self.q.put((chunk if chunk else None, time.monotonic()))
                if not chunk:
                    break
        except Exception as e:  # noqa: BLE001
            self.q.put((e, time.monotonic()))

    def get(self, timeout):
        """Return (chunk, timestamp). chunk None => EOF. Raises on timeout."""
        try:
            chunk, ts = self.q.get(timeout=timeout)
        except queue.Empty:
            raise TimeoutError(f"[{self.label}] no bytes for {timeout}s")
        if isinstance(chunk, Exception):
            raise RuntimeError(f"[{self.label}] pump error: {chunk}")
        if chunk:
            self.bytes_out += len(chunk)
        return chunk

    def close(self):
        self._stop.set()
        reap_process(self.proc, f"pump-close {self.label}")
        CHILDREN.discard(self.proc)


def stream_ffmpeg_to_client(handler, proc, label):
    """Pipe a supervised ffmpeg's MPEG-TS to the HTTP client.

    Raises TimeoutError if the first byte is late or the stream stalls.
    Broken pipes (tuner went away) are normal and swallowed.
    """
    pump = StreamPump(proc, label)
    try:
        first = pump.get(FIRST_BYTE_TIMEOUT)
        if first is None:
            raise RuntimeError(f"[{label}] ffmpeg exited with no output")
        handler.send_response(200)
        handler.send_header("Content-Type", "video/mp2t")
        handler.send_header("Cache-Control", "no-cache")
        handler.end_headers()
        handler.wfile.write(first)
        handler.wfile.flush()
        log.info("[%s] streaming started (pid=%s)", label, proc.pid)
        while True:
            chunk = pump.get(STALL_TIMEOUT)
            if chunk is None:
                log.info("[%s] ffmpeg EOF after %d bytes",
                         label, pump.bytes_out)
                break
            handler.wfile.write(chunk)
            handler.wfile.flush()
    except (BrokenPipeError, ConnectionResetError):
        log.info("[%s] client disconnected after %d bytes",
                 label, pump.bytes_out)
    finally:
        pump.close()


